CREATE TABLE configuracao_jogo(
  id_configuracao int generated by default as identity primary key,
  id_jogador int not null,
  volume_geral int,
  volume_musica int,
  volume_sfx int,
  resolucao_tela varchar(20),
  modo_janela boolean,
  sensibilidade_mouse decimal(5,2),
  data_ultima_atualizacao timestamp
); 


CREATE TABLE partida (
id_partida INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
id_jogador INT NOT NULL,
dias_sobrevividos INT,
tempo_jogado_segundos INT,
resultado VARCHAR(50) NOT NULL,
causa_morte VARCHAR(50),
data_inicio TIMESTAMP,
data_fim TIMESTAMP
);
